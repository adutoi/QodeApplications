# Reference spin-adapted fragment densities from an exact Fock-space FCI (Jordan-Wigner),
# for small fragments only.  They define the density conventions expected by the
# spin-adapted XR machinery:
#
#     <I S_I S_I| T^K_q |J S_J S_J> = <S_J S_J K q|S_I S_I> rho_IJ,     q = S_I - S_J
#
# for proper spherical tensors  c_{+1/2} = c_alpha, c_{-1/2} = c_beta,
#                               at_{+1/2} = a_beta,  at_{-1/2} = -a_alpha
# and the coupled tensors T^K_q(path) of density_providers/spin_tensors.py (hummr's convention for the
# lowering types, adjoints for the raising ones), e.g.
#     a     at_s
#     caa   E_pr at_s  (restr_ca 1, E_pr = sum_s c_ps a_rs, operator-local pair (p,r))
#     aa    [at_p x at_r]^K
#     ca    rank 0: E_pr,   rank 1: T^1 = -sqrt(2) [c_p x at_r]^1  (T^1_0 = n_alpha - n_beta)
#     ccaa  (restr_ca 2) sum_{s,t} c_ps c_rt a_ss a_tt
# The densities are computed directly from these operators, for all paths.  The adjoint ("raising") types
# are generated by the density provider by reversal (density_providers/dens_util.reversed_densities_spin_adapt)
# and are only produced here for testing that reversal.

import itertools
import numpy as np
import scipy.sparse as sps
from sympy import Rational
from sympy.physics.quantum.cg import CG

def cg(j1, m1, j2, m2, J, M):
    R = lambda x: Rational(int(round(2 * x)), 2)
    return float(CG(R(j1), R(m1), R(j2), R(m2), R(J), R(M)).doit())

def jordan_wigner(n_so):
    I, Z = sps.identity(2, format="csr"), sps.diags([1., -1.], format="csr")
    lower = sps.csr_matrix(np.array([[0., 1.], [0., 0.]]))
    ops = []
    for i in range(n_so):
        mats = [Z] * i + [lower] + [I] * (n_so - i - 1)
        op = mats[0]
        for m in mats[1:]:
            op = sps.kron(op, m, format="csr")
        ops.append(op)
    return ops

def second_quantized_H(h, W, n_orb, a, c):
    """H = sum h_pq c_ps a_qs + sum W_pqrs c_ps c_qt a_st a_rs  (W_pqrs = 1/2 (pr|qs), XR convention)"""
    A = lambda p, s: a[2 * p + s]
    C = lambda p, s: c[2 * p + s]
    H = sps.csr_matrix(a[0].shape)
    for p, q in itertools.product(range(n_orb), repeat=2):
        if abs(h[p, q]) > 1e-14:
            H += h[p, q] * sum(C(p, s) @ A(q, s) for s in range(2))
    for p, q, r, t in itertools.product(range(n_orb), repeat=4):
        if abs(W[p, q, r, t]) > 1e-14:
            H += W[p, q, r, t] * sum(C(p, s) @ C(q, u) @ A(t, u) @ A(r, s) for s in range(2) for u in range(2))
    return H

def spin_operators(n_orb, a, c):
    A = lambda p, s: a[2 * p + s]
    C = lambda p, s: c[2 * p + s]
    N = sum(C(p, s) @ A(p, s) for p in range(n_orb) for s in range(2))
    Sz = 0.5 * sum(C(p, 0) @ A(p, 0) - C(p, 1) @ A(p, 1) for p in range(n_orb))
    Sp = sum(C(p, 0) @ A(p, 1) for p in range(n_orb))
    return N, Sz, Sp

def high_spin_eigenstates(H, N, Sz, Sp, n_elec, allowed=None):
    """
    {(n_elec, mult): matrix with the M=S eigenvectors of H as columns}
    allowed: optional boolean mask of the Fock-space basis states to diagonalize in (e.g. frozen core)
    """
    dense = lambda x: x.toarray() if sps.issparse(x) else x
    H, N, Sz, Sp = dense(H), dense(N), dense(Sz), dense(Sp)
    if not np.allclose(H, H.T, atol=1e-12):
        raise ValueError("high_spin_eigenstates uses eigh and requires a hermitian H (e.g. not the biorthogonal one)")
    S2 = Sp.T @ Sp + Sz @ Sz + Sz
    nd, sd = np.round(np.diag(N)).astype(int), np.round(2 * np.diag(Sz)).astype(int)
    out = {}
    for n in range(nd.max() + 1):
        if n_elec is not None and n != n_elec:
            continue
        for twoS in range(n % 2, n + 1, 2):
            idx = np.where((nd == n) & (sd == twoS) & (True if allowed is None else allowed))[0]
            if len(idx) == 0:
                continue
            w, v = np.linalg.eigh(S2[np.ix_(idx, idx)])
            S = twoS / 2
            P = v[:, np.abs(w - S * (S + 1)) < 1e-8]
            if P.shape[1] == 0:
                continue
            e, u = np.linalg.eigh(P.T @ H[np.ix_(idx, idx)] @ P)
            vecs = np.zeros((H.shape[0], P.shape[1]))
            vecs[idx] = P @ u
            for k in range(vecs.shape[1]):    # deterministic phase
                j = np.argmax(np.abs(vecs[:, k]) > 1e-8)
                vecs[:, k] *= np.sign(vecs[j, k])
            out[(n, twoS + 1)] = (e, vecs)
    return out


class Fragment(object):
    """exact spin-adapted states and densities of a small fragment"""
    def __init__(self, h, W, n_orb, n_elec_ref, frozen_core=0):
        """frozen_core: number of core orbitals (the first ones), which are doubly occupied in every state"""
        self.n, self.n_ref, self.n_core = n_orb, n_elec_ref, frozen_core
        self.a = jordan_wigner(2 * n_orb)
        self.c = [x.T for x in self.a]
        self.A = lambda p, s: self.a[2 * p + s]
        self.C = lambda p, s: self.c[2 * p + s]
        self.H = second_quantized_H(h, W, n_orb, self.a, self.c)
        N, self.Sz, self.Sp = spin_operators(n_orb, self.a, self.c)
        allowed = None
        if frozen_core > 0:
            n_core_el = sum(self.C(K, s) @ self.A(K, s) for K in range(frozen_core) for s in range(2))
            n_core_el = n_core_el.diagonal() if sps.issparse(n_core_el) else np.diag(n_core_el)
            allowed = np.round(n_core_el).astype(int) == 2 * frozen_core
        self.states = {(n_elec_ref - n, mult): vecs
                       for (n, mult), (e, vecs) in high_spin_eigenstates(self.H, N, self.Sz, self.Sp, None, allowed).items()}
        self.ct = lambda p, m: self.C(p, 0) if m > 0 else self.C(p, 1)
        self.at = lambda p, m: self.A(p, 1) if m > 0 else -self.A(p, 0)
        self.E = lambda p, r: sum(self.C(p, s) @ self.A(r, s) for s in range(2))

    def m_states(self, chg, mult, i):
        """{M: vector} of state i of sector (chg, mult), generated from M=S by S_-"""
        v = self.states[(chg, mult)][:, i]
        S = (mult - 1) / 2
        out, M = {S: v}, S
        while M > -S + 1e-9:
            v = self.Sp.T @ v
            v = v / np.linalg.norm(v)
            M -= 1
            out[round(M, 1)] = v
        return out

    def leg(self, kind, p, m2):
        """single operator of a leg: c_m or at_m"""
        if kind == "c":
            return self.C(p, 0 if m2 > 0 else 1)
        return self.A(p, 1) if m2 > 0 else -self.A(p, 0)

    def density(self, name, restr, path, si, sj):
        """
        density of type name (operator string with all c's before the a's), coupling path and restr_ca
        between the sectors si (bra) and sj (ket) = (charge, mult), in the CG convention; None if forbidden
        """
        from spin_tensors import components, path_rank2, cg2
        n_c, n_a = name.count("c"), name.count("a")
        Si2, Sj2 = si[1] - 1, sj[1] - 1
        K2 = path_rank2(path)
        f = cg2(Sj2, Sj2, K2, Si2 - Sj2, Si2, Si2)
        if abs(f) < 1e-12:
            return None
        comps = components(n_c, n_a, path, Si2 - Sj2)
        kinds = ["c"] * n_c + ["a"] * n_a
        Vi, Vj = self.states[si], self.states[sj]
        N = n_c + n_a
        out = np.zeros((Vi.shape[1], Vj.shape[1]) + (self.n,) * N)
        for m, c in comps.items():
            # apply the legs from the right, sharing the common suffixes of the index tuples
            level = {(): sps.csr_matrix(Vj)}
            for t in reversed(range(N)):
                level = {(p,) + idx: self.leg(kinds[t], p, m[t]) @ v for idx, v in level.items() for p in range(self.n)}
                level = {idx: v for idx, v in level.items() if v.nnz > 0}
            for idx, v in level.items():
                out[(slice(None), slice(None)) + idx] += c * (Vi.T @ v.toarray())
        return out / f

    def densities(self, charges, types):
        """{name: {(chg_bra, chg_ket): {(mult_bra, mult_ket, rank2, restr_ca, path): density}}} of the given (name, restr)"""
        from spin_tensors import paths
        secs = [s for s in self.states if s[0] in charges]
        out = {}
        for name, restr in types:
            n_c, n_a = name.count("c"), name.count("a")
            out.setdefault(name, {})
            for si, sj in itertools.product(secs, repeat=2):
                if si[0] - sj[0] != n_a - n_c:
                    continue
                for K2 in range((n_c + n_a) % 2, n_c + n_a + 1, 2):
                    for path in paths(n_c, n_a, K2, restr):
                        v = self.density(name, restr, path, si, sj)
                        if v is not None:
                            out[name].setdefault((si[0], sj[0]), {})[(si[1], sj[1], K2, restr, path)] = v
        return out

    def lowering_densities(self, charges, xr_level=0):
        """the density types returned by hummr for xr_level, in the reference (CG) convention"""
        return self.densities(charges, hummr_types(xr_level))

    def raising_densities(self, charges, xr_level=0):
        """the adjoint types, only for testing the reversal of the density provider"""
        from dens_util import adjoint_name
        return self.densities(charges, [(adjoint_name(name), restr) for name, restr in hummr_types(xr_level)
                                        if adjoint_name(name) != name])


def hummr_types(xr_level):
    """(name, restr_ca) of the densities computed by hummr up to xr_level"""
    types = [("a", 0), ("aa", 0), ("ca", 0), ("ca", 1), ("caa", 1), ("ccaa", 2)]
    if xr_level >= 1:
        types += [("caa", 0), ("ccaa", 1), ("caaa", 1), ("ccaaa", 2)]
    if xr_level >= 2:
        types += [("ccaa", 0), ("caaa", 0), ("ccaaa", 1), ("ccaaaa", 2), ("cccaaa", 2)]
    return types


def as_hummr_output(dens):
    """
    Convert reference densities into the raw form returned by hummr (see
    density_providers/hummr_dens/pybind_interface.to_cg_convention), so that they pass
    through exactly the same wrapping/reversal/conversion code as hummr's densities:
    stretched elements and only mult_bra <= mult_ket for the charge-conserving (self-adjoint) types.
    """
    out = {}
    for name, dd in dens.items():
        self_adjoint = name.count("c") == name.count("a")
        for cp, chans in dd.items():
            for ch, t in chans.items():
                mb, mk, r2, rc, path = ch
                if self_adjoint and mb > mk:
                    continue
                SI, SJ = (mb - 1) / 2, (mk - 1) / 2
                t = t * cg(SJ, SJ, r2 / 2, SI - SJ, SI, SI)
                out.setdefault(name, {}).setdefault(cp, {})[ch] = t
    return out


class ReferenceBackend(object):
    """drop-in replacement for density_providers.dens_provider.DensBackend (densities only)"""
    def __init__(self, fragment, charges, active_only=False):
        """
        active_only: (frozen-core fragment) hand only the active block of the densities to the density
                     provider, like hummr does, so that they pass through its frozen-core embedding
        """
        self.fragment, self.charges, self.active_only = fragment, charges, active_only
        self._cache = {}
    def build_densities(self, frag_name, xr_level, bra_states, ket_states):
        from hummr_dens.pybind_interface import wrap_dens_and_build_transpose
        if xr_level not in self._cache:
            self._cache[xr_level] = as_hummr_output(self.fragment.lowering_densities(self.charges, xr_level))
        dens = self._cache[xr_level]
        # wrap_dens_and_build_transpose consumes its input (empties it, converts the arrays in place): pass copies
        if not self.active_only:
            return wrap_dens_and_build_transpose({name: {cp: {ch: t.copy() for ch, t in chans.items()} for cp, chans in dd.items()}
                                                  for name, dd in dens.items()})
        nc = self.fragment.n_core
        act = {name: {cp: {ch: t[(slice(None), slice(None)) + (slice(nc, None),) * (t.ndim - 2)].copy() for ch, t in chans.items()}
                      for cp, chans in dd.items()} for name, dd in dens.items()}
        return wrap_dens_and_build_transpose(act, n_core=nc, n_mo=self.fragment.n)
    def placeholder_states(self):
        """state dictionary with the right number of states per sector (the vectors are not used)"""
        out = {}
        for (chg, mult), vecs in self.fragment.states.items():
            if chg in self.charges:
                out.setdefault(chg, {})[mult] = [None] * vecs.shape[1]
        return out


# ---------------------------------------------------------------------------------------------------------------
# Spin-orbital reference (the original formalism of the XR diagrams): densities of all M components of the states
# ---------------------------------------------------------------------------------------------------------------

SO_TYPES = ["a", "aa", "c", "ca", "caa", "caaa", "cc", "cca", "ccaa", "ccaaa", "ccaaaa", "ccca", "cccaa", "cccaaa", "ccccaa"]

def so_states(frag, charges):
    """{chg: [(mult, i, M, vector)]}: all M components (from S_-) of the states of each charge"""
    out = {}
    for chg in charges:
        for mult in sorted(m for c, m in frag.states if c == chg):
            for i in range(frag.states[(chg, mult)].shape[1]):
                for M, v in sorted(frag.m_states(chg, mult, i).items(), reverse=True):
                    out.setdefault(chg, []).append((mult, i, M, v))
    return out

def so_densities(frag, charges, n_elec_ref, types=SO_TYPES):
    """
    spin-orbital densities <I M|c_x1 .. c_xn a_y1 .. a_ym|J M'> (spin orbitals blocked per fragment: alpha orbitals,
    then beta, as the spin-orbital integrals of get_ints), in the structure of the density provider with the
    multiplicity None
    """
    from hummr_dens.pybind_interface import _tens_wrap
    n = frag.n
    states = so_states(frag, charges)
    op = lambda kind, x: (frag.C if kind == "c" else frag.A)(x % n, x // n)
    rho = {}
    for name in types:
        n_c, n_a = name.count("c"), name.count("a")
        for ci, cj in itertools.product(charges, repeat=2):
            if ci - cj != n_a - n_c:
                continue
            Vi = np.array([v for *_, v in states[ci]]).T
            Vj = np.array([v for *_, v in states[cj]]).T
            out = np.zeros((Vi.shape[1], Vj.shape[1]) + (2 * n,) * len(name))
            for idx in itertools.product(range(2 * n), repeat=len(name)):
                v = Vj
                for t in reversed(range(len(name))):
                    v = op(name[t], idx[t]) @ v
                out[(slice(None), slice(None)) + idx] = Vi.T @ v
            rho.setdefault(name, {})[(ci, cj)] = {(None,) * 5: _tens_wrap(out)}
    rho["n_states"] = {chg: {None: len(states[chg])} for chg in charges}
    rho["n_states_bra"] = rho["n_states"]
    rho["n_elec"] = {chg: n_elec_ref - chg for chg in charges}
    rho["overlap"] = {chg: {None: np.eye(len(states[chg]))} for chg in charges}
    return rho, states
